/** 把 .env 里看不到的「本次客户语种」变成一句明确要求，避免西语客户收到英文回信 */
const LANG_CN: Record<string, string> = {
  es: '西班牙语', fr: '法语', pt: '葡萄牙语', ru: '俄语', ar: '阿拉伯语',
  ja: '日语', ko: '韩语', de: '德语', it: '意大利语', en: '英语', zh: '中文',
};

function dynamicRules(req: UnifiedRequest): string {
  const locale = String(req.context?.locale ?? '').trim();
  const prefix = locale.split(/[-_]/)[0].toLowerCase();
  const langNote = locale
    ? `本次客户使用的是${LANG_CN[prefix] ?? locale}，回复稿正文必须用${LANG_CN[prefix] ?? locale}写。`
    : '回复稿正文必须使用与客户消息完全相同的语言（只有客户本人用中文提问时才用中文）。';
  return [
    `7. ${langNote}`,
    '8. 正文用纯文本，不要用 ** 加粗、# 标题、- 列表等 Markdown 符号，微信里会显示成星号。',
    '9. 整份答复只写一遍【回复稿】【中文翻译】【中文说明】，不要重复输出，也不要出现 <think> 标签或任何内部思考过程。',
  ].join('\n');
}

/** 把「本机资料库现在有什么」也告诉模型，否则它不知道该按什么型号去查 */
function libraryBrief(): string {
  const index = getIndex();
  if (!index) {
    return '\n【本机资料库】尚未整理；涉及价格、型号、货期时先调用 quote_lookup，程序会自动整理一次再查。';
  }
  const examples = index.型号目录
    .filter((m) => /[A-Za-z]/.test(m.型号))
    .slice(0, 5)
    .map((m) => m.型号);
  return (
    `\n【本机资料库】已整理 ${index.统计.报价表数} 个报价表、${index.统计.型号数} 个型号、${index.统计.报价行数} 行报价；` +
    `型号示例：${examples.join('、') || '（暂无编码型号，可用产品名搜）'}。` +
    `问价、问款式、问交期一律先调用工具；客户用中文问到的产品名也要用 library_search 搜资料库。` +
    `注意：库存数量、可选型号与产品图会随实际库存表变化，当前库存表尚未更新，工具没返回就写「待人工补充」。`
  );
}

/**
 * 网关注入系统提示词，避免各 Agent 各自实现。
 * 同时把「话术经验库」拼进去：客服标记的成功 / 失败案例会在下一次起草时生效，
 * 换任何 Agent 都能吃到同一份经验（这是统一网关的好处）。
 *
 * 以前只有「经验库非空」时才注入，导致没有样本时外部 AI 根本收不到格式要求；
 * 现在无论有没有经验，格式规则都会带上，并用幂等判断避免多轮调用重复注入。
 */
export function ensureSystemPrompt(req: UnifiedRequest): UnifiedRequest {
  const userText = [...req.messages].reverse().find((m) => m.role === 'user')?.content ?? '';
  const intent = classifyIntent(userText);
  const extra = scriptPromptExtra(intent);
  const rules = `${CS_SYSTEM_PROMPT}\n${dynamicRules(req)}${extra.trim() ? `\n${extra}` : ''}${libraryBrief()}`;

  if (req.messages[0]?.role === 'system') {
    const first = req.messages[0];
    if (first.content.includes('【中文翻译】')) return req;
    return {
      ...req,
      messages: [{ ...first, content: `${first.content}\n${rules}` }, ...req.messages.slice(1)],
    };
  }
  return { ...req, messages: [{ role: 'system', content: rules }, ...req.messages] };
}
